BEGIN;

-- Workspace rows can be read tenant-wide by the trusted API, but the API may
-- only create a row for the currently authenticated user. Only the worker may
-- update lifecycle state, and its column grants are independently restricted.
DROP POLICY tenant_isolation ON public.workspaces;
CREATE POLICY workspace_tenant_read ON public.workspaces
  FOR SELECT USING (
    tenant_id = NULLIF(current_setting('cornod.tenant_id', true), '')::uuid
  );
CREATE POLICY workspace_creator_insert ON public.workspaces
  FOR INSERT WITH CHECK (
    tenant_id = NULLIF(current_setting('cornod.tenant_id', true), '')::uuid
    AND created_by = NULLIF(current_setting('cornod.user_id', true), '')::uuid
  );
CREATE POLICY workspace_worker_update ON public.workspaces
  FOR UPDATE
  USING (
    current_user = 'cornod_worker'
    AND tenant_id = NULLIF(current_setting('cornod.tenant_id', true), '')::uuid
  )
  WITH CHECK (
    current_user = 'cornod_worker'
    AND tenant_id = NULLIF(current_setting('cornod.tenant_id', true), '')::uuid
  );

-- Application-created events must identify the authenticated actor. Worker
-- events are system events and therefore use a NULL actor_id.
DROP POLICY tenant_isolation ON public.workspace_events;
CREATE POLICY workspace_event_tenant_read ON public.workspace_events
  FOR SELECT USING (
    tenant_id = NULLIF(current_setting('cornod.tenant_id', true), '')::uuid
  );
CREATE POLICY workspace_event_actor_insert ON public.workspace_events
  FOR INSERT WITH CHECK (
    tenant_id = NULLIF(current_setting('cornod.tenant_id', true), '')::uuid
    AND (
      (current_user = 'cornod_app' AND actor_id = NULLIF(current_setting('cornod.user_id', true), '')::uuid)
      OR (current_user = 'cornod_worker' AND actor_id IS NULL)
    )
  );

-- Audit writes must be attributable to the verified API user.
DROP POLICY tenant_isolation ON public.audit_events;
CREATE POLICY audit_event_tenant_read ON public.audit_events
  FOR SELECT USING (
    tenant_id = NULLIF(current_setting('cornod.tenant_id', true), '')::uuid
  );
CREATE POLICY audit_event_actor_insert ON public.audit_events
  FOR INSERT WITH CHECK (
    current_user = 'cornod_app'
    AND tenant_id = NULLIF(current_setting('cornod.tenant_id', true), '')::uuid
    AND actor_id = NULLIF(current_setting('cornod.user_id', true), '')::uuid
  );

-- Usage is generated by trusted metering, never by a tenant-facing API request.
REVOKE INSERT ON public.usage_ledger FROM cornod_app;
GRANT SELECT, INSERT ON public.usage_ledger TO cornod_worker;
GRANT USAGE, SELECT ON SEQUENCE public.workspace_events_id_seq TO cornod_worker;
GRANT USAGE, SELECT ON SEQUENCE public.usage_ledger_id_seq TO cornod_worker;

COMMIT;
